#!/usr/bin/env python3
"""
Rasterise public/resume.pdf into the page images the in-page viewer shows.

Run this by hand whenever resume.pdf changes — the images are committed, so
nothing at build time depends on Python being installed:

    pip install Pillow
    # Install Poppler (pdftoppm), or set PDFTOPPM to its executable path.
    python3 scripts/render-resume.py

The PDF stays the source of truth: the viewer's download and open-in-a-tab
actions both serve public/resume.pdf directly. These images only exist so the
résumé can be read inside the page, on a phone, without the browser's PDF
plugin — which on iOS renders a single unscrollable page in an iframe.
"""

import hashlib
import json
import os
import pathlib
import shutil
import subprocess
import tempfile

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
PDF = ROOT / "public" / "resume.pdf"
OUT = ROOT / "public" / "resume"

# 2x a 72dpi page, so the sheets stay crisp on a retina display without the
# files getting silly.
DPI = 144
QUALITY = 82


def main() -> None:
    pdftoppm = os.environ.get("PDFTOPPM") or shutil.which("pdftoppm")
    if not pdftoppm:
        raise SystemExit("Poppler is required: install pdftoppm or set PDFTOPPM.")

    version = hashlib.sha256(PDF.read_bytes()).hexdigest()[:12]
    OUT.mkdir(parents=True, exist_ok=True)
    pages = []
    with tempfile.TemporaryDirectory(prefix="resume-pages-") as tmp:
        prefix = pathlib.Path(tmp) / "page"
        subprocess.run([pdftoppm, "-png", "-r", str(DPI), str(PDF), str(prefix)], check=True)
        rendered = sorted(pathlib.Path(tmp).glob("page-*.png"),
                          key=lambda path: int(path.stem.rsplit("-", 1)[1]))
        if not rendered:
            raise SystemExit("Poppler did not render any pages.")
        for i, source in enumerate(rendered, start=1):
            with Image.open(source) as rendered_image:
                img = rendered_image.convert("RGB")
                dest = OUT / f"page-{i}.webp"
                img.save(dest, "WEBP", quality=QUALITY, method=6)
                page_version = hashlib.sha256(dest.read_bytes()).hexdigest()[:12]
                pages.append({"page": i, "w": img.width, "h": img.height,
                              "version": page_version})
                print(f"{dest.relative_to(ROOT)}  {img.width}x{img.height}  "
                      f"{dest.stat().st_size / 1024:.0f} KB")

    for stale in OUT.glob("page-*.webp"):
        if int(stale.stem.rsplit("-", 1)[1]) > len(pages):
            stale.unlink()

    manifest = ROOT / "content" / "resume.ts"
    rows = "\n".join(
        f"  {{ page: {page['page']}, w: {page['w']}, h: {page['h']}, version: \"{page['version']}\" }},"
        for page in pages
    )
    manifest.write_text('''/**
 * In-page resume images, generated by scripts/render-resume.py.
 * Rerun the script whenever public/resume.pdf changes; it refreshes this
 * manifest as well as the previews. Explicit dimensions prevent layout shift.
 */

export interface ResumePage {
  page: number;
  w: number;
  h: number;
  version: string;
}

export const RESUME_VERSION = "''' + version + '''";
export const RESUME_PDF = `/resume.pdf?v=${RESUME_VERSION}`;

export const RESUME_PAGES: ResumePage[] = [
''' + rows + "\n];\n")
    print("Updated content/resume.ts:")
    print(json.dumps(pages, indent=2))


if __name__ == "__main__":
    main()
